"""Check standalone HTML copies in an offline browser and preserve screenshots."""
import asyncio
import json
import pathlib
import re
import shutil
from html.parser import HTMLParser
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parents[1]
ISOLATED = ROOT / "checks/isolated"
ISOLATED.mkdir(exist_ok=True)
manifest = json.loads((ROOT / "build/delivery-manifest.json").read_text())

class ResourceParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.resources = []
    def handle_starttag(self, tag, attrs):
        for k, v in attrs:
            if k in ("src", "href", "srcset", "poster") and v:
                self.resources.append((tag, k, v))

static = []
for m in manifest:
    p = ROOT / m["file"]
    text = p.read_text()
    assert text.startswith("<!-- Generated by Trae Work -->")
    parser = ResourceParser()
    parser.feed(text)
    external = [r for r in parser.resources if not r[2].startswith(("#", "data:", "blob:"))]
    assert not external, external
    assert not re.search(r"\bsk-[A-Za-z0-9_-]{18,}\b", text), "Possible API key"
    assert not re.search(r"Bearer\s+[A-Za-z0-9_-]{18,}", text), "Possible bearer token"
    static.append({"file": m["file"], "external_resources": external, "api_key_patterns": 0})
    shutil.copyfile(p, ISOLATED / p.name)

async def main():
    results = []
    async with async_playwright() as pw:
        browser = await pw.chromium.launch(
            executable_path="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
            headless=True, args=["--disable-background-networking"])
        for m in manifest:
            ctx = await browser.new_context(offline=True, viewport={"width": 1440, "height": 1050}, device_scale_factor=1)
            page = await ctx.new_page()
            errors, requests = [], []
            page.on("pageerror", lambda e: errors.append(str(e)))
            page.on("request", lambda req: requests.append(req.url) if not req.url.startswith(("file:", "data:", "blob:")) else None)
            await page.goto((ISOLATED / m["file"]).as_uri(), wait_until="load", timeout=60000)
            await page.wait_for_function("!!window.__casebook", timeout=30000)
            n = await page.evaluate("window.__casebook.data.cases.length")
            assert n == m["cases"], (m["file"], n)
            # Decode every embedded asset, including images hidden in subsequent rounds.
            decoded = await page.evaluate("""async () => {
              const failures=[];const entries=Object.entries(window.__casebook.data.assets);
              for(const [h,a] of entries){
                const im=new Image();im.src=window.__casebook.assetURL(h);
                try{await im.decode();if(im.naturalWidth!==a.width||im.naturalHeight!==a.height) failures.push(h)}
                catch(e){failures.push(h+":"+e.message)}
                im.removeAttribute('src');
              }
              return {count:entries.length,failures};
            }""")
            assert not decoded["failures"], decoded
            ids = await page.evaluate("window.__casebook.data.cases.map(c=>[c.dataset,c.id])")
            record_checks = []
            for ds, qid in ids:
                await page.evaluate("([ds,id])=>window.__casebook.select(ds,id)", [ds, qid])
                await page.locator(".case-title").wait_for()
                rounds = page.locator(".round-detail")
                count = await rounds.count()
                for j in range(count):
                    rd = rounds.nth(j)
                    await rd.locator("summary").first.click()
                    await rd.locator(".round-body > .source-note").wait_for()
                    # Exercise exact request rendering and all nested image references.
                    inp = rd.locator(".sub-detail").first
                    await inp.locator("summary").first.click()
                    await inp.locator(".message").first.wait_for()
                    await inp.locator("summary").first.click()
                    # Validate thinking availability and tool/metadata details rendering.
                    for detail in await rd.locator(".sub-detail").all():
                        if await detail.get_attribute("open") is None:
                            await detail.locator("summary").first.click()
                            await detail.locator(".sub-body").wait_for()
                            await detail.locator("summary").first.click()
                    await rd.locator("summary").first.click()
                # Force deferred VSI gallery once; confirms all 32 frames can be rendered.
                if ds == "VSIbench":
                    await page.locator(".all-frames > summary").click()
                    await page.locator(".all-frames .image-card").last.wait_for()
                    assert await page.locator(".all-frames .image-card").count() == 32
                    await page.locator(".all-frames > summary").click()
                record_checks.append({"dataset": ds, "id": qid, "rounds_rendered": count})
            await page.evaluate("([ds,id])=>window.__casebook.select(ds,id)", ids[0])
            await page.locator("[data-image]").first.click()
            await page.wait_for_function("document.querySelector('#lightbox-img').complete && document.querySelector('#lightbox-img').naturalWidth>0")
            assert await page.locator("#lightbox").evaluate("(d)=>d.open")
            await page.keyboard.press("Escape")
            assert not await page.locator("#lightbox").evaluate("(d)=>d.open")
            # Test sidebar search and dataset tabs using visible UI, then restore first case.
            await page.locator("#search").fill(ids[-1][1])
            assert await page.locator(".case-button").count() >= 1
            await page.locator("#search").fill("")
            if m["file"] == "index.html":
                await page.locator('[data-dataset="BLINK"]').click()
                assert await page.locator(".case-button").count() == 5
                await page.locator('[data-dataset="全部"]').click()
            await page.evaluate("([ds,id])=>window.__casebook.select(ds,id)", ids[0])
            await page.evaluate("window.scrollTo(0,0)")
            await page.screenshot(path=str(ROOT / "checks" / (m["file"].replace(".html", "-desktop.png"))), animations="disabled")
            await page.set_viewport_size({"width": 390, "height": 844})
            await page.evaluate("window.scrollTo(0,0)")
            overflow = await page.evaluate("({width:innerWidth,scroll:document.documentElement.scrollWidth})")
            assert overflow["scroll"] <= overflow["width"] + 1, overflow
            await page.screenshot(path=str(ROOT / "checks" / (m["file"].replace(".html", "-mobile.png"))), animations="disabled")
            assert not errors, errors
            assert not requests, requests
            results.append({"file": m["file"], "offline": True, "only_html_copied": True,
                            "cases": n, "assets_decoded": decoded["count"],
                            "case_records": record_checks, "external_requests": requests,
                            "javascript_errors": errors, "mobile_overflow": overflow,
                            "search_navigation_lightbox": "passed"})
            print(json.dumps({k: v for k, v in results[-1].items() if k != "case_records"}, ensure_ascii=False), flush=True)
            await ctx.close()
        await browser.close()
    (ROOT / "checks/offline-browser-validation.json").write_text(
        json.dumps({"static": static, "browser": results}, ensure_ascii=False, indent=2))

asyncio.run(main())
