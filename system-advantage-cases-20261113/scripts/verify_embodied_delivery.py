"""Exercise real standalone readers in offline Chrome using visible controls."""
import argparse
import asyncio
from collections import Counter
import hashlib
from html.parser import HTMLParser
import json
import pathlib
import re
import shutil
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parents[1]
COPY = ROOT / "checks/isolated"
COPY.mkdir(exist_ok=True)
parser = argparse.ArgumentParser()
parser.add_argument("--files", nargs="*")
args = parser.parse_args()
manifest = json.loads((ROOT / "build/delivery-manifest.json").read_text())
manifest = [m for m in manifest if not args.files or m["file"] in args.files]

class Resources(HTMLParser):
    def __init__(self):
        super().__init__()
        self.external = []
    def handle_starttag(self, tag, attrs):
        for name, value in attrs:
            if name in ("src", "href", "srcset", "poster") and value and not value.startswith(("#", "data:", "blob:")):
                self.external.append([tag, name, value])

for m in manifest:
    path = ROOT / m["file"]
    raw = path.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == m["sha256"]
    text = raw.decode()
    assert text.startswith("<!-- Generated by Trae Work -->")
    assert "__HEADLINE__" not in text and "__SCOPE__" not in text
    resources = Resources()
    resources.feed(text)
    assert not resources.external, resources.external
    assert not re.search(r"\bsk-[A-Za-z0-9_-]{18,}\b", text)
    assert not re.search(r"Bearer\s+[A-Za-z0-9_-]{18,}", text)
    shutil.copyfile(path, COPY / path.name)

async def main():
    results = []
    async with async_playwright() as pw:
        browser = await pw.chromium.launch(
            executable_path="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
            headless=True, args=["--disable-background-networking"])
        for m in manifest:
            context = await browser.new_context(offline=True, viewport={"width": 1440, "height": 1050})
            page = await context.new_page()
            errors, external = [], []
            page.on("pageerror", lambda e: errors.append(str(e)))
            page.on("request", lambda r: external.append(r.url) if not r.url.startswith(("file:", "data:", "blob:")) else None)
            await page.goto((COPY / m["file"]).as_uri(), timeout=60000, wait_until="load")
            await page.wait_for_function("!!window.__casebook", timeout=30000)
            data = await page.evaluate("""() => window.__casebook.data.cases.map(c => ({
                id:c.id,dataset:c.dataset,kind:c.kind||'qa',actions:c.actions?.length,
                observations:c.observations?.length,requests:c.requests?.length,
                system_rounds:c.arms?.system.rounds.length,direct_rounds:c.arms?.direct.rounds.length
            }))""")
            assert len(data) == m["cases"]
            assert all(n == 5 for n in Counter(c["dataset"] for c in data).values())
            if m["file"] == "index.html":
                assert data[0]["kind"] == "embodied"
                assert len([c for c in data if c["kind"] == "qa"]) == 30
            decoded = await page.evaluate("""async () => {
                const failed=[];const entries=Object.entries(window.__casebook.data.assets);
                for(const [h,a] of entries){
                    const im=new Image();im.src=window.__casebook.assetURL(h);
                    try{await im.decode();if(im.naturalWidth!==a.width||im.naturalHeight!==a.height)failed.push(h)}
                    catch(e){failed.push(h+':'+e.message)}
                    im.removeAttribute('src');
                }
                return {count:entries.length,failed};
            }""")
            assert not decoded["failed"], decoded
            print(m["file"], "decoded", decoded["count"], flush=True)
            record_checks = []
            # The twenty unique embodied traces receive full action/request inspection here.
            deep_embodied = m["file"] == "EmbodiedBench.html" or args.files == ["EB-Manipulation.html"]
            for c in data:
                # Select through the actual tab and sidebar.
                await page.locator(f'[data-dataset="{c["dataset"]}"]').click()
                button = page.locator('[data-case=' + json.dumps(c["dataset"] + "::" + c["id"]) + ']')
                assert await button.count() == 1
                await button.click()
                await page.locator(".case-title").wait_for()
                if c["kind"] == "embodied":
                    assert await page.locator(".snapshot-gallery .image-card").count() == 3
                    assert await page.locator(".action-row").count() == c["actions"]
                    assert await page.locator(".embodied-request").count() == c["requests"]
                    assert await page.locator("#traces").count() == 0
                    assert await page.locator(".snapshot-gallery").is_visible()
                    if deep_embodied:
                        for action in await page.locator(".action-row").all():
                            serial = await action.get_attribute("data-observation")
                            await action.click()
                            assert f"观察 {serial} /" in await page.locator("#observation-caption").inner_text()
                            assert await page.locator("#observation-gallery img").count() >= 2
                    else:
                        await page.locator(".action-row").last.click()
                        assert "任务成功" in await page.locator("#observation-caption").inner_text()
                    if deep_embodied:
                        for req in await page.locator(".embodied-request").all():
                            await req.locator("summary").first.click()
                            await req.locator(".round-body > .source-note").wait_for()
                            inp = req.locator(".sub-detail").first
                            await inp.locator("summary").first.click()
                            await inp.locator(".message").first.wait_for()
                            assert await req.locator(".response-code").inner_text()
                            await inp.locator("summary").first.click()
                            await req.locator("summary").first.click()
                    # Exercise the keyboard-based observation control.
                    slider = page.locator("#observation-range")
                    await slider.focus()
                    await slider.press("Home")
                    assert await slider.input_value() == "0"
                    await slider.press("End")
                    assert await slider.input_value() == str(c["observations"] - 1)
                else:
                    assert await page.locator("#traces .system").count() == 1
                    assert await page.locator("#traces .direct").count() == 1
                    assert await page.locator(".round-detail").count() == c["system_rounds"] + c["direct_rounds"]
                    # QA details are fully checked in the six independent dataset files.
                    if m["file"] not in ("index.html", "EmbodiedBench.html"):
                        for rd in await page.locator(".round-detail").all():
                            await rd.locator("summary").first.click()
                            await rd.locator(".round-body > .source-note").wait_for()
                            inp = rd.locator(".sub-detail").first
                            await inp.locator("summary").first.click()
                            await inp.locator(".message").first.wait_for()
                            await inp.locator("summary").first.click()
                            assert await rd.locator(".response-code").count() == 1
                            await rd.locator("summary").first.click()
                        if c["dataset"] == "VSIbench":
                            await page.locator(".all-frames > summary").click()
                            await page.locator(".all-frames .image-card").last.wait_for()
                            assert await page.locator(".all-frames .image-card").count() == 32
                            await page.locator(".all-frames > summary").click()
                record_checks.append({**c, "visible_content": "passed",
                                      "full_trace": c["kind"] == "embodied" and deep_embodied or c["kind"] == "qa" and m["file"] != "index.html"})
            first = data[0]
            await page.locator(f'[data-dataset="{first["dataset"]}"]').click()
            await page.locator(".case-button").first.click()
            await page.locator("[data-image]").first.click()
            await page.wait_for_function("document.querySelector('#lightbox-img').complete && document.querySelector('#lightbox-img').naturalWidth>0")
            assert await page.locator("#lightbox").evaluate("(d)=>d.open")
            await page.keyboard.press("Escape")
            assert not await page.locator("#lightbox").evaluate("(d)=>d.open")
            await page.locator("#search").fill(first["id"])
            assert await page.locator(".case-button").count() == 1
            await page.locator("#search").fill("")
            await page.locator(".case-button").first.click()
            await page.locator(".case-title").scroll_into_view_if_needed()
            await page.screenshot(path=str(ROOT / "checks" / m["file"].replace(".html", "-content-desktop.png")), animations="disabled")
            await page.set_viewport_size({"width": 390, "height": 844})
            await page.locator(".case-title").scroll_into_view_if_needed()
            overflow = await page.evaluate("({viewport:innerWidth,scroll:document.documentElement.scrollWidth})")
            assert overflow["scroll"] <= overflow["viewport"] + 1, overflow
            await page.screenshot(path=str(ROOT / "checks" / m["file"].replace(".html", "-content-mobile.png")), animations="disabled")
            assert not errors, errors
            assert not external, external
            result = {"file": m["file"], "sha256": m["sha256"], "offline": True,
                      "only_html_copied": True, "cases": len(data), "assets_decoded": decoded["count"],
                      "records": record_checks, "external_requests": external,
                      "javascript_errors": errors, "mobile_overflow": overflow,
                      "visible_navigation_search_slider_zoom": "passed"}
            results.append(result)
            (ROOT / "checks" / m["file"].replace(".html", "-embodied-delivery-validation.json")).write_text(
                json.dumps(result, ensure_ascii=False, indent=2))
            print(m["file"], "PASS", len(data), "cases", flush=True)
            await context.close()
        await browser.close()
    return results

asyncio.run(main())
